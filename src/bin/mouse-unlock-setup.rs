fn ui(f: &mut Frame, app: &App) {
    let chunks = Layout::default()
        .direction(Direction::Vertical)
        .constraints([
            Constraint::Length(9),
            Constraint::Min(8),
            Constraint::Length(3),
        ])
        .split(f.area());

    f.render_widget(
        Paragraph::new(info_lines(app)).block(block(" Mouse Unlock — Setup ")),
        chunks[0],
    );
    f.render_widget(
        Paragraph::new(action_lines(app)).block(block(" Actions ")),
        chunks[1],
    );
    f.render_widget(
        Paragraph::new(app.status.clone())
            .block(block(" Status "))
            .wrap(Wrap { trim: true }),
        chunks[2],
    );
}

fn block(title: &str) -> Block<'_> {
    Block::default()
        .borders(Borders::ALL)
        .border_type(BorderType::Rounded)
        .title(Span::styled(
            title,
            Style::default().add_modifier(Modifier::BOLD),
        ))
}

fn label(text: &str) -> Span<'static> {
    Span::styled(
        text.to_string(),
        Style::default()
            .fg(Color::Gray)
            .add_modifier(Modifier::BOLD),
    )
}

fn click_spans(clicks: &[Click]) -> Vec<Span<'static>> {
    let mut spans = Vec::new();
    for (i, c) in clicks.iter().enumerate() {
        if i > 0 {
            spans.push(Span::raw(" "));
        }
        spans.push(Span::styled(
            c.label().to_string(),
            Style::default().fg(c.color()).add_modifier(Modifier::BOLD),
        ));
    }
    spans
}

fn info_lines(app: &App) -> Vec<Line<'static>> {
    let mut lines: Vec<Line> = Vec::new();

    let shown = if app.mode == Mode::Recording {
        &app.record_buf
    } else {
        &app.pattern
    };
    let mut pat = vec![label("Pattern : ")];
    if shown.is_empty() {
        pat.push(Span::styled("(none)", Style::default().fg(Color::DarkGray)));
    } else {
        pat.extend(click_spans(shown));
    }
    lines.push(Line::from(pat));

    lines.push(Line::from(vec![
        label("Timeout : "),
        Span::raw(format!("{} ms", app.timeout_ms)),
    ]));
    lines.push(Line::from(vec![
        label("Unlock  : "),
        Span::raw(app.unlock_cmd.clone()),
    ]));

    let root = if is_root() {
        Span::styled("root: yes", Style::default().fg(Color::Green))
    } else {
        Span::styled(
            "root: no (sudo needed to install)",
            Style::default().fg(Color::Yellow),
        )
    };
    lines.push(Line::from(vec![
        label("Config  : "),
        Span::raw(config_target()),
        Span::raw("   "),
        root,
    ]));

    match app.mode {
        Mode::Recording => lines.push(Line::from(Span::styled(
            "● REC — click Left / Right / Middle in this window",
            Style::default().fg(Color::Red).add_modifier(Modifier::BOLD),
        ))),
        Mode::EditTimeout => lines.push(Line::from(vec![
            Span::styled("New timeout (ms): ", Style::default().fg(Color::Cyan)),
            Span::raw(format!("{}_", app.input)),
        ])),
        Mode::EditCmd => lines.push(Line::from(vec![
            Span::styled("New unlock cmd: ", Style::default().fg(Color::Cyan)),
            Span::raw(format!("{}_", app.input)),
        ])),
        Mode::Normal => {}
    }

    lines
}

fn key(k: &str) -> Span<'static> {
    Span::styled(
        format!("[{k}]"),
        Style::default()
            .fg(Color::Yellow)
            .add_modifier(Modifier::BOLD),
    )
}

fn action_lines(app: &App) -> Vec<Line<'static>> {
    match app.mode {
        Mode::Recording => vec![
            Line::from("Click in this window to add:  Left=L   Right=R   Middle=M"),
            Line::from(vec![
                key("Backspace"),
                Span::raw(" undo last   "),
                key("Enter"),
                Span::raw(" save   "),
                key("Esc"),
                Span::raw(" cancel"),
            ]),
        ],
        Mode::EditTimeout | Mode::EditCmd => vec![
            Line::from("Type a value, then confirm."),
            Line::from(vec![
                key("Enter"),
                Span::raw(" confirm   "),
                key("Esc"),
                Span::raw(" cancel   "),
                key("Backspace"),
                Span::raw(" delete"),
            ]),
        ],
        Mode::Normal => vec![
            Line::from(vec![
                key("r"),
                Span::raw(" Record pattern     "),
                key("c"),
                Span::raw(" Clear pattern"),
            ]),
            Line::from(vec![
                key("t"),
                Span::raw(" Edit timeout       "),
                key("u"),
                Span::raw(" Edit unlock cmd"),
            ]),
            Line::from(""),
            Line::from(vec![
                key("1"),
                Span::raw(" Save config        "),
                key("2"),
                Span::raw(" Install service"),
            ]),
            Line::from(vec![
                key("3"),
                Span::raw(" Save + Install     "),
                key("4"),
                Span::raw(" Uninstall service"),
            ]),
            Line::from(""),
            Line::from(vec![key("q"), Span::raw(" Quit")]),
        ],
    }
}

