fn setup_terminal() -> io::Result<Terminal<CrosstermBackend<Stdout>>> {
    enable_raw_mode()?;
    let mut stdout = io::stdout();
    execute!(stdout, EnterAlternateScreen, EnableMouseCapture)?;
    Terminal::new(CrosstermBackend::new(stdout))
}

fn restore_terminal() -> io::Result<()> {
    disable_raw_mode()?;
    execute!(io::stdout(), LeaveAlternateScreen, DisableMouseCapture)?;
    Ok(())
}

fn is_root() -> bool {
    unsafe { libc::geteuid() == 0 }
}

fn require_root() -> Result<(), String> {
    if is_root() {
        Ok(())
    } else {
        Err("needs root — re-run with: sudo mouse-unlock-setup".into())
    }
}

/// Where `save config` writes: /etc when root, otherwise the current directory.
fn config_target() -> String {
    if is_root() {
        CONFIG_PATH.to_string()
    } else {
        "mouse-unlock.conf (cwd)".to_string()
    }
}

fn sh(cmd: &str) -> Result<(), String> {
    let out = Command::new("sh")
        .arg("-c")
        .arg(cmd)
        .output()
        .map_err(|e| e.to_string())?;
    if out.status.success() {
        Ok(())
    } else {
        let err = String::from_utf8_lossy(&out.stderr);
        Err(format!("`{cmd}` failed: {}", err.trim()))
    }
}

fn find_daemon_binary() -> Option<PathBuf> {
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Ok(exe) = std::env::current_exe() {
        if let Some(dir) = exe.parent() {
            candidates.push(dir.join("mouse-unlock"));
        }
    }
    candidates.push(PathBuf::from("target/release/mouse-unlock"));
    candidates.push(PathBuf::from("target/debug/mouse-unlock"));
    candidates.push(PathBuf::from(DAEMON_DEST));
    candidates.into_iter().find(|p| p.is_file())
}

/// Parse /etc/mouse-unlock.conf if present; otherwise return defaults.
fn load_config() -> (Vec<Click>, u64, String) {
    let mut pattern = parse_pattern("LLRRL");
    let mut timeout_ms = 2000u64;
    let mut unlock_cmd = String::from("loginctl unlock-sessions");

    if let Ok(content) = fs::read_to_string(CONFIG_PATH) {
        for line in content.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            if let Some((k, v)) = line.split_once('=') {
                let (k, v) = (k.trim(), v.trim());
                match k {
                    "pattern" => {
                        let p = parse_pattern(v);
                        if !p.is_empty() {
                            pattern = p;
                        }
                    }
                    "timeout_ms" => {
                        if let Ok(n) = v.parse::<u64>() {
                            timeout_ms = n;
                        }
                    }
                    "unlock_cmd" => {
                        if !v.is_empty() {
                            unlock_cmd = v.to_string();
                        }
                    }
                    _ => {}
                }
            }
        }
    }
    (pattern, timeout_ms, unlock_cmd)
}

fn parse_pattern(s: &str) -> Vec<Click> {
    s.chars()
        .filter_map(|c| match c.to_ascii_uppercase() {
            'L' => Some(Click::Left),
            'R' => Some(Click::Right),
            'M' => Some(Click::Middle),
            _ => None,
        })
        .collect()
}
